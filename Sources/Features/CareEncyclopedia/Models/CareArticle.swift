// MARK: - Категории компонентов устройства для ухода
public enum CareCategory: String, CaseIterable, Identifiable, Sendable {
    case ports = "Разъемы и зарядка"
    case screen = "Дисплей и олеофобка"
    case battery = "Аккумулятор и нагрев"
    case body = "Корпус и чехлы"
    case optics = "Камеры и оптика"
    case audio = "Акустика и микрофоны"
    
    public var id: String { rawValue }
    
    public var iconName: String {
        switch self {
        case .ports: return "cable.connector"
        case .screen: return "iphone"
        case .battery: return "battery.100.bolt"
        case .body: return "shield.lefthalf.filled"
        case .optics: return "camera.fill"
        case .audio: return "speaker.wave.3.fill"
        }
    }
    
    public var color: Color {
        switch self {
        case .ports: return Color(hex: "00B4D8")
        case .screen: return Color(hex: "00F5D4")
        case .battery: return Color(hex: "06D6A0")
        case .body: return Color(hex: "FFB703")
        case .optics: return Color(hex: "9D4EDD")
        case .audio: return Color(hex: "F72585")
        }
    }
}

// MARK: - Модель статьи руководства по уходу
public struct CareArticle: Identifiable, Sendable {
    public let id: String
    public let category: CareCategory
    public let title: String
    public let subtitle: String
    public let readTimeMinutes: Int
    public let keyRules: [String]
    public let prohibitedActions: [String]
    public let detailedGuide: [ArticleSection]
    
    public init(
        id: String,
        category: CareCategory,
        title: String,
        subtitle: String,
        readTimeMinutes: Int,
        keyRules: [String],
        prohibitedActions: [String],
        detailedGuide: [ArticleSection]
    ) {
        self.id = id
        self.category = category
        self.title = title
        self.subtitle = subtitle
        self.readTimeMinutes = readTimeMinutes
        self.keyRules = keyRules
        self.prohibitedActions = prohibitedActions
        self.detailedGuide = detailedGuide
    }
}

public struct ArticleSection: Identifiable, Sendable {
    public let id = UUID()
    public let heading: String
    public let content: String
    public let proTip: String?
    
    public init(heading: String, content: String, proTip: String? = nil) {
        self.heading = heading
        self.content = content
        self.proTip = proTip
    }
}

